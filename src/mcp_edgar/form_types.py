"""Bundled catalogue of EDGAR submission-type codes (req_002 v2.04).

``data/form_types.json`` is generated by ``scripts/refresh_form_types.py`` before a release from the
quarterly EDGAR full index (filing counts over the last four completed quarters) and the SEC Forms
List (descriptions and topics where the form number matches). ``list_form_types`` serves it
offline: no request reaches the SEC at call time (gotchas #20). The ``form`` values are exactly
the strings the filing tools accept in ``forms`` and return in ``form``.
"""

from __future__ import annotations

import functools
import json
import logging
import re
from dataclasses import dataclass
from importlib import resources
from typing import Any

logger = logging.getLogger(__name__)

DATA_FILE = "form_types.json"
MAX_QUERY_LENGTH = 100
_DATE_RE = re.compile(r"\d{4}-\d{2}-\d{2}")
_QUARTER_RE = re.compile(r"\d{4}Q[1-4]")


class CatalogueError(ValueError):
    """The bundled catalogue is missing or malformed: a packaging bug, surfaced, never masked."""


class InvalidQuery(ValueError):
    """``query`` is not a string of at most ``MAX_QUERY_LENGTH`` characters."""


@dataclass(frozen=True, slots=True)
class FormType:
    """One EDGAR submission-type code with its snapshot statistics and Forms List decoration."""

    form: str
    description: str | None
    amendment: bool
    filings: int
    topics: tuple[str, ...]

    def as_dict(self) -> dict[str, Any]:
        return {
            "form": self.form,
            "description": self.description,
            "amendment": self.amendment,
            "filings": self.filings,
            "topics": list(self.topics),
        }

    def matches(self, needle: str) -> bool:
        """Case-insensitive substring match on the code or the description (``needle`` lowered)."""
        if needle in self.form.lower():
            return True
        return self.description is not None and needle in self.description.lower()


def _entry(raw: Any, index: int) -> FormType:
    if not isinstance(raw, dict):
        raise CatalogueError(f"form_types[{index}] is not an object")
    form, description = raw.get("form"), raw.get("description")
    amendment, filings, topics = raw.get("amendment"), raw.get("filings"), raw.get("topics")
    if not isinstance(form, str) or not form.strip() or form != form.strip():
        raise CatalogueError(f"form_types[{index}] has an invalid form {form!r}")
    if description is not None and (not isinstance(description, str) or not description):
        raise CatalogueError(f"form_types[{index}] ({form}) has an invalid description")
    if not isinstance(amendment, bool) or amendment != form.endswith("/A"):
        raise CatalogueError(f"form_types[{index}] ({form}) has an inconsistent amendment flag")
    if isinstance(filings, bool) or not isinstance(filings, int) or filings < 1:
        raise CatalogueError(f"form_types[{index}] ({form}) has an invalid filings count")
    if not isinstance(topics, list) or not all(isinstance(t, str) and t for t in topics):
        raise CatalogueError(f"form_types[{index}] ({form}) has invalid topics")
    return FormType(form, description, amendment, filings, tuple(topics))


@dataclass(frozen=True, slots=True)
class FormTypeCatalogue:
    """The validated snapshot: metadata plus entries sorted by filings desc, then code."""

    generated_on: str
    quarters: tuple[str, ...]
    sources: tuple[str, ...]
    entries: tuple[FormType, ...]

    @classmethod
    def from_payload(cls, payload: Any) -> FormTypeCatalogue:
        """Validate the JSON shape strictly; anything off raises ``CatalogueError``."""
        if not isinstance(payload, dict):
            raise CatalogueError("catalogue is not a JSON object")
        generated_on, quarters = payload.get("generated_on"), payload.get("quarters")
        sources, raw_entries = payload.get("sources"), payload.get("form_types")
        if not isinstance(generated_on, str) or not _DATE_RE.fullmatch(generated_on):
            raise CatalogueError(f"generated_on must be YYYY-MM-DD, got {generated_on!r}")
        if (
            not isinstance(quarters, list)
            or not quarters
            or not all(isinstance(q, str) and _QUARTER_RE.fullmatch(q) for q in quarters)
        ):
            raise CatalogueError("quarters must be a non-empty list like ['2025Q4']")
        if not isinstance(sources, list) or not all(isinstance(s, str) for s in sources):
            raise CatalogueError("sources must be a list of strings")
        if not isinstance(raw_entries, list) or not raw_entries:
            raise CatalogueError("form_types must be a non-empty list")
        entries = tuple(_entry(raw, i) for i, raw in enumerate(raw_entries))
        forms = [entry.form for entry in entries]
        if len(set(forms)) != len(forms):
            raise CatalogueError("form_types contains duplicate codes")
        expected = sorted(entries, key=lambda entry: (-entry.filings, entry.form))
        if forms != [entry.form for entry in expected]:
            raise CatalogueError("form_types must be sorted by filings desc, then form")
        return cls(generated_on, tuple(quarters), tuple(sources), entries)

    @classmethod
    def load(cls) -> FormTypeCatalogue:
        """Read and validate the bundled ``data/form_types.json``."""
        try:
            resource = resources.files("mcp_edgar").joinpath("data").joinpath(DATA_FILE)
            text = resource.read_text(encoding="utf-8")
        except OSError as exc:  # FileNotFoundError included
            raise CatalogueError(f"bundled {DATA_FILE} is missing: {exc}") from exc
        try:
            payload = json.loads(text)
        except ValueError as exc:
            raise CatalogueError(f"bundled {DATA_FILE} is not valid JSON: {exc}") from exc
        catalogue = cls.from_payload(payload)
        logger.debug(
            "form-type catalogue loaded: %d codes, generated %s",
            len(catalogue.entries),
            catalogue.generated_on,
        )
        return catalogue

    def search(self, query: str | None) -> list[FormType]:
        """Entries whose code or description contains ``query`` (case-insensitive); all if None."""
        if query is None:
            return list(self.entries)
        needle = query.lower()
        return [entry for entry in self.entries if entry.matches(needle)]

    def metadata(self) -> dict[str, Any]:
        return {
            "generated_on": self.generated_on,
            "quarters": list(self.quarters),
            "sources": list(self.sources),
        }


def validate_query(query: object) -> str | None:
    """``None``/blank → ``None``; a stripped string of at most ``MAX_QUERY_LENGTH`` characters."""
    if query is None:
        return None
    if not isinstance(query, str):
        raise InvalidQuery(f"query must be a string, got {query!r}")
    text = query.strip()
    if not text:
        return None
    if len(text) > MAX_QUERY_LENGTH:
        raise InvalidQuery(f"query must be at most {MAX_QUERY_LENGTH} characters, got {len(text)}")
    return text


@functools.lru_cache(maxsize=1)
def get_catalogue() -> FormTypeCatalogue:
    """Process-wide catalogue, loaded on first use."""
    return FormTypeCatalogue.load()


def reset_catalogue() -> None:
    """Forget the cached catalogue (tests only)."""
    get_catalogue.cache_clear()
